#!/usr/bin/env python3
"""Generate an LVGL icon font from Material Design Icons.

Renders the glyphs listed in ICONS with FreeType into a 4 bpp, uncompressed
lv_font_fmt_txt font (the same layout lv_font_conv emits), already wrapped in
the UNIT_TEST guard and extern declaration this repo needs.

The font is the TTF from the @mdi/font npm package, e.g.
https://registry.npmjs.org/@mdi/font/-/font-7.4.47.tgz
(package/fonts/materialdesignicons-webfont.ttf).

Usage:
  python scripts/gen_icon_font.py materialdesignicons-webfont.ttf 36
  python scripts/gen_icon_font.py materialdesignicons-webfont.ttf 56

Requires: pip install freetype-py
"""

import argparse
import pathlib

import freetype

# Keep in sync with components/alarmclock/ui_icons.h.
ICONS = {
    "fan": 0xF0210,
    "lightbulb": 0xF0335,
    "lightbulb-outline": 0xF0336,
    "power": 0xF0425,
    "power-plug": 0xF06A5,
    "power-plug-off": 0xF06A6,
    "snowflake": 0xF0717,
    "fan-off": 0xF081D,
    "gesture-tap-button": 0xF12A8,
}

MDI_VERSION = "7.4.47"


def render_glyph(face, codepoint):
    face.load_char(codepoint, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
    glyph = face.glyph
    bitmap = glyph.bitmap
    width, rows, pitch = bitmap.width, bitmap.rows, bitmap.pitch
    pixels = []
    for y in range(rows):
        for x in range(width):
            pixels.append(bitmap.buffer[y * pitch + x] >> 4)
    # LVGL packs 4 bpp pixels as one continuous stream, high nibble first.
    packed = bytearray()
    for i in range(0, len(pixels), 2):
        high = pixels[i]
        low = pixels[i + 1] if i + 1 < len(pixels) else 0
        packed.append((high << 4) | low)
    return {
        "codepoint": codepoint,
        "adv_w": round(glyph.advance.x / 4),  # 26.6 fixed point -> 1/16 px
        "box_w": width,
        "box_h": rows,
        "ofs_x": glyph.bitmap_left,
        "ofs_y": glyph.bitmap_top - rows,
        "bitmap": bytes(packed),
    }


def format_bytes(data, indent="    ", per_line=16):
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i : i + per_line]
        lines.append(indent + ", ".join(f"0x{b:02x}" for b in chunk))
    return ",\n".join(lines)


def generate(font_path, size, name):
    face = freetype.Face(str(font_path))
    face.set_pixel_sizes(0, size)

    glyphs = [render_glyph(face, cp) for cp in sorted(ICONS.values())]
    top = max(g["ofs_y"] + g["box_h"] for g in glyphs)
    bottom = min(g["ofs_y"] for g in glyphs)
    line_height = top - bottom
    base_line = -bottom

    bitmap = bytearray()
    dsc_lines = [
        "    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, "
        ".ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */"
    ]
    for glyph in glyphs:
        dsc_lines.append(
            f"    {{.bitmap_index = {len(bitmap)}, .adv_w = {glyph['adv_w']}, "
            f".box_w = {glyph['box_w']}, .box_h = {glyph['box_h']}, "
            f".ofs_x = {glyph['ofs_x']}, .ofs_y = {glyph['ofs_y']}}}"
        )
        bitmap += glyph["bitmap"]

    range_start = glyphs[0]["codepoint"]
    range_length = glyphs[-1]["codepoint"] - range_start + 1
    unicode_list = ", ".join(
        f"0x{g['codepoint'] - range_start:x}" for g in glyphs
    )
    names = ", ".join(
        f"{n} (U+{cp:X})" for n, cp in sorted(ICONS.items(), key=lambda i: i[1])
    )
    guard = name.upper()

    return f"""/*******************************************************************************
 * Size: {size} px
 * Bpp: 4
 * Generated by scripts/gen_icon_font.py from materialdesignicons-webfont.ttf
 *   (@mdi/font {MDI_VERSION}).
 * Glyphs: {names}
 *
 * Font: Material Design Icons
 * Copyright Pictogrammers (https://pictogrammers.com)
 * Licensed under the Apache License, Version 2.0.
 *   See LICENSES/Apache-2.0-MDI.txt
 ******************************************************************************/
#ifndef UNIT_TEST

#include "lvgl.h"

#ifndef {guard}
#define {guard} 1
#endif

#if {guard}

/*-----------------
 *    BITMAPS
 *----------------*/

/*Store the image of the glyphs*/
static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
{format_bytes(bitmap)}
}};


/*---------------------
 *  GLYPH DESCRIPTION
 *--------------------*/

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{(","+chr(10)).join(dsc_lines)}
}};

/*---------------------
 *  CHARACTER MAPPING
 *--------------------*/

static const uint16_t unicode_list_0[] = {{
    {unicode_list}
}};

/*Collect the unicode lists and glyph_id offsets*/
static const lv_font_fmt_txt_cmap_t cmaps[] =
{{
    {{
        .range_start = {range_start}, .range_length = {range_length}, .glyph_id_start = 1,
        .unicode_list = unicode_list_0, .glyph_id_ofs_list = NULL, .list_length = {len(glyphs)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
    }}
}};

/*--------------------
 *  ALL CUSTOM DATA
 *--------------------*/

#if LVGL_VERSION_MAJOR == 8
/*Store all the custom data of the font*/
static  lv_font_fmt_txt_glyph_cache_t cache;
#endif

#if LVGL_VERSION_MAJOR >= 8
static const lv_font_fmt_txt_dsc_t font_dsc = {{
#else
static lv_font_fmt_txt_dsc_t font_dsc = {{
#endif
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 1,
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
#if LVGL_VERSION_MAJOR == 8
    .cache = &cache
#endif
}};


/*-----------------
 *  PUBLIC FONT
 *----------------*/

/*Initialize a public general font descriptor*/
#if LVGL_VERSION_MAJOR >= 8
extern const lv_font_t {name};
const lv_font_t {name} = {{
#else
lv_font_t {name} = {{
#endif
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,    /*Function pointer to get glyph's data*/
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,    /*Function pointer to get glyph's bitmap*/
    .line_height = {line_height},          /*The maximum line height required by the font*/
    .base_line = {base_line},             /*Baseline measured from the bottom of the line*/
#if !(LVGL_VERSION_MAJOR == 6 && LVGL_VERSION_MINOR == 0)
    .subpx = LV_FONT_SUBPX_NONE,
#endif
#if LV_VERSION_CHECK(7, 4, 0) || LVGL_VERSION_MAJOR >= 8
    .underline_position = 0,
    .underline_thickness = 0,
#endif
    .dsc = &font_dsc,          /*The custom font data. Will be accessed by `get_glyph_bitmap/dsc` */
#if LV_VERSION_CHECK(8, 2, 0) || LVGL_VERSION_MAJOR >= 9
    .fallback = NULL,
#endif
    .user_data = NULL,
}};


#endif /*#if {guard}*/

#endif  // UNIT_TEST
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("font", type=pathlib.Path, help="MDI TTF file")
    parser.add_argument("size", type=int, help="pixel size")
    parser.add_argument(
        "--out-dir",
        type=pathlib.Path,
        default=pathlib.Path(__file__).resolve().parent.parent
        / "components"
        / "alarmclock",
    )
    args = parser.parse_args()
    name = f"icon_font_{args.size}"
    out = args.out_dir / f"{name}.cpp"
    out.write_text(generate(args.font, args.size, name), newline="\n")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
