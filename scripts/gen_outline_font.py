#!/usr/bin/env python3
"""Derive an outline-only variant of the clock font.

Reads a lv_font_conv generated font (4 bpp, uncompressed) and hollows out every
glyph, keeping only a stroke of --stroke pixels along its edge. Metrics,
kerning and glyph boxes are untouched, so the outline font is a drop-in
replacement that lays out exactly like the solid one. Lighting far fewer pixels
keeps the clock readable but much less bright at night.

Usage:
  python scripts/gen_outline_font.py components/alarmclock/clock_font_160.cpp \
      components/alarmclock/clock_font_160_outline.cpp --stroke 5

Requires: pip install numpy pillow
"""

import argparse
import pathlib
import re

import numpy as np
from PIL import Image

SUPERSAMPLE = 4

BITMAP_RE = re.compile(
    r"(static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap\[\] = \{\n)"
    r"(.*?)(\n\};)",
    re.S,
)
DSC_RE = re.compile(
    r"\.bitmap_index = (\d+), \.adv_w = \d+, \.box_w = (\d+), \.box_h = (\d+)"
)


def unpack_4bpp(data, width, height):
    nibbles = np.empty(len(data) * 2, dtype=np.uint8)
    nibbles[0::2] = data >> 4
    nibbles[1::2] = data & 0x0F
    return nibbles[: width * height].reshape(height, width)


def pack_4bpp(pixels):
    flat = pixels.reshape(-1)
    if len(flat) % 2:
        flat = np.append(flat, 0)
    return ((flat[0::2] << 4) | flat[1::2]).astype(np.uint8)


def erode_disk(mask, radius):
    """Binary erosion by a disk, via one sliding-window AND per row offset."""
    pad = radius + 1
    padded = np.pad(mask, pad)
    height, width = padded.shape
    result = np.ones_like(padded)
    window_cache = {}
    for dy in range(-radius, radius + 1):
        half = int((radius * radius - dy * dy) ** 0.5)
        if half not in window_cache:
            csum = np.pad(np.cumsum(padded, axis=1, dtype=np.int32), ((0, 0), (1, 0)))
            full = np.zeros_like(padded)
            lo = np.clip(np.arange(width) - half, 0, width)
            hi = np.clip(np.arange(width) + half + 1, 0, width)
            inside = (np.arange(width) - half >= 0) & (np.arange(width) + half < width)
            full[:, inside] = (csum[:, hi[inside]] - csum[:, lo[inside]]) == (2 * half + 1)
            window_cache[half] = full
        shifted = np.roll(window_cache[half], -dy, axis=0)
        if dy > 0:
            shifted[height - dy :, :] = False
        elif dy < 0:
            shifted[: -dy, :] = False
        result &= shifted
    return result[pad:-pad, pad:-pad]


def outline_glyph(alpha, stroke):
    height, width = alpha.shape
    big = Image.fromarray((alpha * 17).astype(np.uint8)).resize(
        (width * SUPERSAMPLE, height * SUPERSAMPLE), Image.BICUBIC
    )
    solid = np.asarray(big) >= 128
    inner = erode_disk(solid, int(round(stroke * SUPERSAMPLE)))
    ring = (solid & ~inner).astype(np.float32)
    coverage = ring.reshape(height, SUPERSAMPLE, width, SUPERSAMPLE).mean(axis=(1, 3))
    outline = np.rint(coverage * 15).astype(np.uint8)
    # Keep the original anti-aliasing on the outer edge.
    return np.minimum(outline, alpha)


def convert(source, stroke, name_from, name_to):
    bitmap_match = BITMAP_RE.search(source)
    values = re.findall(r"0x([0-9a-fA-F]{1,2})\b", bitmap_match.group(2))
    data = np.array([int(v, 16) for v in values], dtype=np.uint8)
    out = data.copy()

    for index, w, h in (tuple(map(int, m)) for m in DSC_RE.findall(source)):
        if w == 0 or h == 0:
            continue
        size = (w * h + 1) // 2
        alpha = unpack_4bpp(data[index : index + size], w, h)
        out[index : index + size] = pack_4bpp(outline_glyph(alpha, stroke))

    lines = []
    for i in range(0, len(out), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in out[i : i + 16]) + ",")
    body = "\n".join(lines).rstrip(",")
    result = (
        source[: bitmap_match.start(2)] + body + source[bitmap_match.end(2) :]
    )
    result = result.replace(name_from, name_to).replace(
        name_from.upper(), name_to.upper()
    )
    # The Opts line documents how the solid font was generated; leave it as is.
    result = result.replace(
        f"components/alarmclock/{name_to}.cpp", f"components/alarmclock/{name_from}.cpp"
    )
    header = (
        f" * Outline variant of {name_from} generated by "
        f"scripts/gen_outline_font.py (stroke {stroke} px).\n"
    )
    return result.replace(" *\n * Font: Montserrat Bold", header + " *\n * Font: Montserrat Bold", 1)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("source", type=pathlib.Path)
    parser.add_argument("output", type=pathlib.Path)
    parser.add_argument("--stroke", type=float, default=5.0, help="outline width in px")
    args = parser.parse_args()

    name_from = args.source.stem
    name_to = args.output.stem
    text = args.source.read_text(encoding="utf-8")
    args.output.write_text(
        convert(text, args.stroke, name_from, name_to), encoding="utf-8", newline="\n"
    )


if __name__ == "__main__":
    main()
